import request from './request'

/**
 * 登录认证(文档 26 节)。
 *
 * ⚠️ **这是全项目唯一免令牌的接口组**(除了登录本身,其余接口都要带
 * `Authorization: Bearer <token>`)。带令牌这件事在 `request.js` 的请求拦截器里统一做了,
 * 这里不用管。
 */

/**
 * 登录。
 *
 * 成功后拿到三样:`token` / `expireMinutes` / `user`。
 * 📌 **用户信息在登录响应里一起给了**,不用再补调一次 `/auth/me` ——
 *    登录跳主界面那一瞬间正是最需要它的时候。
 *
 * @param {{ username: string, password: string }} body 密码传**明文**,HTTPS 负责传输安全
 *
 * | 错误 | 场景 | msg |
 * |---|---|---|
 * | 400 | 用户名/密码没传 | 登录名不能为空 / 密码不能为空 |
 * | **401** | **用户名不存在 _或_ 密码错误** | 用户名或密码错误 |
 * | **403** | **账号被冻结 / 已删除** | 账号已被冻结或停用,请联系管理员 |
 *
 * ⚠️ 401 那句"用户名或密码错误"是**两种情况共用**的,后端故意不区分 ——
 *    分开说等于提供了一个"这个用户名存不存在"的探测接口。
 *    所以**不要**写"用户名不存在,请先注册"这种提示。
 */
export const login = body => request.post('/auth/login', body)

/**
 * 登出。无参数。
 *
 * ⚠️ **令牌是无状态的(JWT),服务端不存会话**,所以登出的实质是**前端把本地令牌删掉**。
 *    这个接口本身什么都不做,但仍然照常调一下(保持调用链完整,
 *    将来服务端要做令牌吊销时前端无感)。
 *
 * ⚠️ **已知行为**:登出后那个令牌在过期前**技术上仍然有效** —— 这是无状态令牌的固有取舍,
 *    不是 bug。所以"登出"必须真的清本地存储(见 `utils/token.js` 的 `clearToken`)。
 */
export const logout = () => request.post('/auth/logout')

/**
 * 当前登录用户。返回和登录响应里 `user` 一样的对象(不含密码)。
 *
 * 📌 这个接口**每次都会回库查一遍账号状态** —— 所以管理员刚把某人冻结,
 *    那个人下一个请求就会被踢出去,不用等令牌过期。
 *
 * | 错误 | 场景 |
 * |---|---|
 * | **401** | 令牌无效/过期,**或账号已被冻结/删除** |
 */
export const fetchMe = () => request.get('/auth/me')
